#!/usr/bin/env node
// Builds LifeAsDuburi/Plugins/WebGL/DuburiAudio.jslib from the browser game's
// sound engine (src/ui/audio.js, class Sound): in a WebGL build the Unity port
// plays exactly the same Web Audio graph as the browser version.
//
//   node unity/tools/build-audio-jslib.mjs        (from the repository root, or anywhere)
//
// esbuild (from the repository's node_modules) bundles audio.js into an ES2017
// IIFE that exposes the Sound class; the .jslib wraps it in Emscripten library
// functions that Runtime/Audio/Sound.cs calls through [DllImport("__Internal")]:
//   DuburiAudio_Init()                         create the Sound once, unlock it on the first gesture
//   DuburiAudio_Update(dt, underwater, depth, paused, float* vehicles, count)
//   DuburiAudio_Call(namePtr, a, b, c)         sound[name](a, b, c): one-shots, ensure, setMuted, motor, dispose
// Vehicles are passed as floats, STRIDE per vehicle (keep in sync with Sound.cs):
//   n[0..7] (rotor speed fraction per thruster, NaN = no thruster), maxRpm, blades,
//   size code (0 t200, 1 t500, 2 small), dist, pan
// The generated file is committed; run this again whenever src/ui/audio.js changes.

import { build } from 'esbuild';
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '../..');
const entry = resolve(repo, 'src/ui/audio.js');
const out = resolve(repo, 'unity/LifeAsDuburi/Plugins/WebGL/DuburiAudio.jslib');

const STRIDE = 13;
const MAX_N = 8;

const res = await build({
  entryPoints: [entry],
  bundle: true,
  format: 'iife',
  globalName: '__DuburiSoundModule',
  target: 'es2017',
  platform: 'browser',
  write: false,
  minify: false,
  legalComments: 'none',
  logLevel: 'warning',
});
const bundle = res.outputFiles[0].text.trim();

const indent = (s, pad) => s.split('\n').map((l) => (l ? pad + l : l)).join('\n');

const lib = `// GENERATED by unity/tools/build-audio-jslib.mjs from src/ui/audio.js. Do not edit;
// edit the JavaScript sound engine and run: node unity/tools/build-audio-jslib.mjs
// Web Audio sound for the WebGL build of Life as Duburi (the browser game's engine).

var DuburiAudioLib = {
  $DuburiAudio: {
    sound: null,
    veh: [],
    list: [],
    listener: { underwater: true, depth: 0, paused: false, vehicles: null },
    sizes: ['t200', 't500', 'small'],
  },

  // returns the Sound class of src/ui/audio.js
  $DuburiAudioLoad: function () {
    // ---- bundled src/ui/audio.js (esbuild, ES2017 IIFE) ----
${indent(bundle, '    ')}
    // ---- end of bundle ----
    return __DuburiSoundModule.Sound;
  },

  DuburiAudio_Init__deps: ['$DuburiAudio', '$DuburiAudioLoad'],
  DuburiAudio_Init: function () {
    if (DuburiAudio.sound) return 1;
    try {
      var Sound = DuburiAudioLoad();
      var s = new Sound();
      DuburiAudio.sound = s;
      // Safari (and Chrome's autoplay policy) only let audio start inside a user
      // gesture: unlock on the first pointer / key / touch, and keep resuming
      // after the tab was suspended.
      var unlock = function () { try { s.ensure(); } catch (e) { /* ignore */ } };
      if (typeof document !== 'undefined') {
        document.addEventListener('pointerdown', unlock, true);
        document.addEventListener('keydown', unlock, true);
        document.addEventListener('touchend', unlock, true);
      }
      return 1;
    } catch (e) {
      if (typeof console !== 'undefined') console.warn('Life as Duburi audio unavailable', e);
      return 0;
    }
  },

  DuburiAudio_Update__deps: ['$DuburiAudio'],
  DuburiAudio_Update: function (dt, underwater, depth, paused, vehicles, count) {
    var s = DuburiAudio.sound;
    if (!s) return;
    var L = DuburiAudio.listener, list = DuburiAudio.list, veh = DuburiAudio.veh;
    L.underwater = !!underwater; L.depth = depth; L.paused = !!paused;
    list.length = 0;
    var base = vehicles >> 2;
    for (var i = 0; i < count; i++) {
      var o = veh[i];
      if (!o) { o = veh[i] = { n: [], maxRpm: 3500, blades: 3, size: 't200', dist: 0, pan: 0 }; }
      var p = base + i * ${STRIDE};
      var n = o.n, k = 0;
      for (var j = 0; j < ${MAX_N}; j++) {
        var x = HEAPF32[p + j];
        if (x !== x) break; // NaN: no more thrusters
        n[k++] = x;
      }
      n.length = k;
      o.maxRpm = HEAPF32[p + ${MAX_N}];
      o.blades = HEAPF32[p + ${MAX_N + 1}];
      o.size = DuburiAudio.sizes[HEAPF32[p + ${MAX_N + 2}] | 0] || 't200';
      o.dist = HEAPF32[p + ${MAX_N + 3}];
      o.pan = HEAPF32[p + ${MAX_N + 4}];
      list.push(o);
    }
    L.vehicles = list;
    s.update(dt, L);
  },

  DuburiAudio_Call__deps: ['$DuburiAudio'],
  DuburiAudio_Call: function (name, a, b, c) {
    var s = DuburiAudio.sound;
    if (!s) return 0;
    var m = UTF8ToString(name);
    if (m.charAt(0) === '_' || typeof s[m] !== 'function') return 0;
    var r = s[m](a, b, c);
    return r === false ? 0 : 1;
  },
};

mergeInto(LibraryManager.library, DuburiAudioLib);
`;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, lib);
console.log(`wrote ${out} (${(lib.length / 1024).toFixed(1)} KB)`);
